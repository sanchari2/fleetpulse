"""Command line entry point for CI Doctor.

    python -m ci_doctor.cli --repo owner/name --run-id 123 --dry-run

Environment
    GITHUB_TOKEN        token with actions:read and pull-requests:write
    ANTHROPIC_API_KEY   key for the model endpoint
    CLAUDE_MODEL        primary model id (default in client.py)
    CLAUDE_FALLBACK_MODELS  comma-separated fallbacks tried on refusal

Exit codes: 0 always, unless the arguments are unusable. A failed diagnosis must
never turn a red build into a confusing one.
"""

from __future__ import annotations

import argparse
import os
import sys
from typing import Sequence

import requests

from . import client

COMMENT_MARKER = "<!-- ci-doctor -->"


def build_comment(
    diagnosis: client.Diagnosis | None,
    steps: list[client.FailedStep],
    *,
    run_url: str,
    note: str = "",
) -> str:
    """The Markdown body posted on the pull request."""
    header = [
        COMMENT_MARKER,
        "## CI Doctor",
        "",
    ]
    if steps:
        failed = ", ".join(f"`{step.job_name}`" for step in steps)
        header.append(f"Failed job(s): {failed}")
        if run_url:
            header.append(f"Run: {run_url}")
        header.append("")

    if diagnosis is None:
        header += [
            f"Could not produce a diagnosis. {note}".strip(),
            "",
            "The failure itself is unchanged — read the job log above.",
            "",
        ]
        return "\n".join(header)

    header += [
        diagnosis.text,
        "",
        f"<sub>Model: `{diagnosis.model}` · logs trimmed to the last "
        f"{client.DEFAULT_MAX_LOG_LINES} lines · generated by CI Doctor</sub>",
        "",
    ]
    return "\n".join(header)


def post_comment(session, repo: str, number: str, body: str, token: str) -> int:
    """Create a pull request (or issue) comment. Returns the HTTP status."""
    response = session.post(
        f"{client.GITHUB_API}/repos/{repo}/issues/{number}/comments",
        headers=client._auth_headers(token),
        json={"body": body},
        timeout=30,
    )
    return int(response.status_code)


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="ci_doctor", description="Explain a failed CI run.")
    parser.add_argument("--repo", default=os.getenv("GITHUB_REPOSITORY", ""))
    parser.add_argument("--run-id", default=os.getenv("GITHUB_RUN_ID", ""))
    parser.add_argument(
        "--pr", default=os.getenv("PR_NUMBER", ""), help="PR or issue number to comment on"
    )
    parser.add_argument(
        "--run-url",
        default="",
        help="link to the failed run, for the comment header",
    )
    parser.add_argument("--max-log-lines", type=int, default=client.DEFAULT_MAX_LOG_LINES)
    parser.add_argument("--dry-run", action="store_true", help="print the comment, post nothing")
    return parser


def main(argv: Sequence[str] | None = None, session=None) -> int:
    args = build_parser().parse_args(argv)
    http = session or requests.Session()
    token = os.getenv("GITHUB_TOKEN", "")

    if not args.repo or not args.run_id:
        print("ci_doctor: --repo and --run-id are required", file=sys.stderr)
        return 2
    if not token:
        print("ci_doctor: GITHUB_TOKEN is not set", file=sys.stderr)
        return 2

    try:
        steps = client.collect_failed_steps(http, args.repo, args.run_id, token, args.max_log_lines)
    except client.DoctorError as exc:
        print(f"ci_doctor: could not read the run: {exc}", file=sys.stderr)
        return 0

    if not steps:
        print("ci_doctor: no failed jobs in this run, nothing to do", file=sys.stderr)
        return 0

    diagnosis: client.Diagnosis | None = None
    note = ""
    try:
        diagnosis = client.call_claude(
            client.build_prompt(steps, args.repo, args.run_id),
            api_key=os.getenv("ANTHROPIC_API_KEY", ""),
            models=client.models_from_env(),
            session=http,
        )
    except client.DoctorError as exc:
        note = f"Reason: {exc}."
        print(f"ci_doctor: {exc}", file=sys.stderr)

    body = build_comment(diagnosis, steps, run_url=args.run_url, note=note)

    if args.dry_run or not args.pr:
        print(body)
        return 0

    status = post_comment(http, args.repo, args.pr, body, token)
    if status >= 300:
        print(f"ci_doctor: posting the comment failed with HTTP {status}", file=sys.stderr)
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
